class User {

    String userName, fullName, emailAddr, passW, mobNumber;

    User(
        String fullName,
        String userName,
        String emailAddr,
        String mobNumber,
        String passW
    ) {
        this.fullName = fullName;
        this.userName = userName;
        this.emailAddr = emailAddr;
        this.mobNumber = mobNumber;
        this.passW = passW;
    }
}
